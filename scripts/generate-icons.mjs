// One-off: turns the extension's components/icons.js into a TypeScript data module, so the
// Phosphor paths are never re-typed by hand. Run with: node scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../1.0.1_0/src/components/icons.js');
const out = resolve(here, '../src/components/icons-data.ts');

const src = readFileSync(source, 'utf8');

/** Single-path icons look like `key: (s) => svg("<path d=\"...\"/>", s)`. */
const singles = [...src.matchAll(/^\s{2}(\w+):\s*\(s\)\s*=>\s*svg\("<path d=\\"([^"]+)\\"/gm)];

/** The Google mark is a multi-path SVG in a template literal, with explicit fills. */
const googleBlock = src.match(/google:\s*\(s[^)]*\)\s*=>\s*`([\s\S]*?)`,/);
const google = [...(googleBlock?.[1] ?? '').matchAll(/fill="(#[0-9A-Fa-f]{6})" d="([^"]+)"/g)].map(([, fill, d]) => ({ fill, d }));

const paths = Object.fromEntries(singles.map(([, key, d]) => [key, d]));

if (!paths.paper || !paths.chevron || google.length !== 4 || singles.length !== 27) {
  console.error(`Parse failed: ${singles.length} single icons, ${google.length} google paths`);
  process.exit(1);
}

const banner = `// GENERATED by scripts/generate-icons.mjs from the extension's src/components/icons.js.
// Phosphor Icons 2.1.1 (MIT). The Google mark is the official brand logo. Do not edit by hand.

export const ICON_PATHS: Record<string, string> = ${JSON.stringify(paths, null, 2)};

/** The Google mark carries its own colours, so it is a list of paths rather than one shape. */
export const GOOGLE_PATHS = ${JSON.stringify(google, null, 2)};
`;

writeFileSync(out, banner, 'utf8');
console.log(`Wrote ${out} (${Object.keys(paths).length} icons + Google mark)`);
